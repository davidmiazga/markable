/**
 * Build-time script: strip @font-face rules from KaTeX CSS.
 *
 * KaTeX's default CSS references font files via relative `url(fonts/...)` paths.
 * In a Tauri WebView there is no HTTP server to serve those paths, so the fonts
 * would 404. Rather than embedding ~350 KB of base64 font data (which would push
 * the plugin IIFE over the 500 KB load limit), we simply strip all @font-face
 * declarations. The math layout CSS (~10 KB) is preserved intact, and KaTeX HTML
 * renders correctly using the system's serif fallback fonts.
 *
 * Future improvement: if exact KaTeX font rendering is required, copy the woff2
 * files to src-tauri/fonts/ as Tauri resources and rewrite the url() paths to use
 * the asset:// protocol instead of stripping them.
 *
 * Run: node scripts/inline-katex-fonts.mjs
 * Or:  npm run build:katex-css
 *
 * Regenerate any time KaTeX is upgraded (the KaTeX version is stamped in the output).
 */

import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

// Resolve project root from this script's location (scripts/ is one level down).
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const cssPath = resolve(root, "node_modules/katex/dist/katex.min.css");
const outPath = resolve(root, "src/plugins/math/katex-css.ts");

// ── Step 1: Read KaTeX CSS ────────────────────────────────────────────────────

let css = readFileSync(cssPath, "utf8");
const originalSize = css.length;

// ── Step 2: Strip all @font-face blocks ──────────────────────────────────────
//
// @font-face rules reference `url(fonts/...)` paths that 404 in the Tauri WebView.
// Stripping them entirely keeps only the layout/sizing CSS (~10 KB), which is all
// KaTeX needs to render correct math structure. Glyphs fall back to the system
// serif font, which is acceptable for a note-taking context.
//
// The regex matches each @font-face { ... } block including all whitespace before it.
// The `s` flag makes `.` match newlines so multi-line blocks are captured correctly.

css = css.replace(/\s*@font-face\s*\{[^}]*\}/gs, "").trim();

console.log(
  `[inline-katex-fonts] Stripped @font-face blocks. ` +
  `CSS reduced from ${(originalSize / 1024).toFixed(1)} KB to ${(css.length / 1024).toFixed(1)} KB.`
);

// ── Step 3: Write TypeScript module ──────────────────────────────────────────

const katexVersion = JSON.parse(
  readFileSync(resolve(root, "node_modules/katex/package.json"), "utf8")
).version;

/**
 * The output module exports a single string constant KATEX_CSS.
 * JSON.stringify() is used to produce a valid JS string literal from the CSS,
 * handling embedded backticks, backslashes, and other special characters safely.
 */
const output = [
  `// AUTO-GENERATED by scripts/inline-katex-fonts.mjs — DO NOT EDIT MANUALLY`,
  `// Regenerate by running: node scripts/inline-katex-fonts.mjs`,
  `// KaTeX version: ${katexVersion}`,
  `export const KATEX_CSS: string = ${JSON.stringify(css)};`,
].join("\n") + "\n";

writeFileSync(outPath, output, "utf8");

console.log(
  `[inline-katex-fonts] Written: src/plugins/math/katex-css.ts ` +
  `(KaTeX ${katexVersion}, ${(output.length / 1024).toFixed(1)} KB)`
);
