/**
 * fetch-material-icons.mjs
 *
 * One-time dev script: fetches specific Material Symbols (Outlined, weight 400)
 * SVGs from unpkg.com and saves them locally. Also emits an index.ts with all
 * SVG strings as named exports so the IIFE build can inline them at compile time.
 *
 * Usage: node scripts/fetch-material-icons.mjs
 */

import { mkdir, writeFile } from "fs/promises";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT  = join(__dir, "..");
const OUT   = join(ROOT, "src/plugins/file-browser/icons/material");
const BASE  = "https://unpkg.com/@material-symbols/svg-400@0.44.4/outlined";

/** Icons to download. Key = export name, value = Material Symbols icon name. */
const ICONS = {
  VAULT:           "inventory_2",
  FOLDER:          "folder",
  FOLDER_OPEN:     "folder_open",
  FOLDER_MANAGED:  "folder_managed",    // Smart Folders icon — FR-17 / Locked #7
  FILE:            "description",
  FILE_MD:         "article",
  FILE_IMAGE:      "image",
  FILE_JSON:       "data_object",
  FILE_CODE:       "code",
  CHEVRON:         "chevron_right",
  EXPAND:          "keyboard_arrow_down",
  UNMOUNT:         "chip_extraction",   // Vault unmount button
};

/** Strip width/height attributes so we can set them per-use-site. */
function stripSize(svg) {
  return svg.replace(/\s+width="\d+"/, "").replace(/\s+height="\d+"/, "");
}

async function fetchSvg(name) {
  const url = `${BASE}/${name}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.text();
}

async function main() {
  await mkdir(OUT, { recursive: true });

  const entries = [];

  for (const [exportName, iconName] of Object.entries(ICONS)) {
    process.stdout.write(`Fetching ${iconName}... `);
    try {
      const raw = await fetchSvg(iconName);
      const svg = stripSize(raw).trim();
      // Save individual SVG file
      await writeFile(join(OUT, `${iconName}.svg`), raw);
      entries.push({ exportName, iconName, svg });
      console.log("ok");
    } catch (e) {
      console.log(`FAILED: ${e.message}`);
      process.exitCode = 1;
    }
  }

  // Emit index.ts with all SVG strings as named exports
  const ts = [
    "// AUTO-GENERATED by scripts/fetch-material-icons.mjs — do not edit by hand",
    "// Material Symbols Outlined (weight 400) — https://fonts.google.com/icons",
    "// License: Apache 2.0  https://github.com/marella/material-symbols",
    "",
    ...entries.map(({ exportName, iconName, svg }) =>
      `/** Material Symbols: ${iconName} */\nexport const ICON_${exportName} =\n  \`${svg}\`;\n`
    ),
  ].join("\n");

  await writeFile(join(OUT, "index.ts"), ts);
  console.log(`\nWrote ${entries.length} icons to ${OUT}/index.ts`);
}

main().catch((e) => { console.error(e); process.exit(1); });
